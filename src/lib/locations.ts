/**
 * Returns exact coordinates for any district or state across India.
 */
export function getDistrictCoordinates(
  districtName?: string,
  stateName?: string
): { lat: number; lng: number } {
  if (!districtName || districtName.trim() === "" || districtName.toLowerCase() === "all") {
    if (stateName && STATE_CENTROIDS[stateName]) {
      return STATE_CENTROIDS[stateName];
    }
    return { lat: 28.6139, lng: 77.209 }; // Default to New Delhi, India
  }

  const clean = districtName.trim();

  // 1. Direct key match
  if (DISTRICT_COORDS[clean]) {
    return DISTRICT_COORDS[clean];
  }

  // 2. Case-insensitive / normalized substring match
  const lower = clean.toLowerCase();
  for (const [key, coords] of Object.entries(DISTRICT_COORDS)) {
    const kLower = key.toLowerCase();
    if (kLower === lower || lower.includes(kLower) || kLower.includes(lower)) {
      return coords;
    }
  }

  // 3. Fallback to state centroid if district belongs to known state
  for (const [state, dists] of Object.entries(LOCATIONS)) {
    if (dists.some((d) => d.toLowerCase() === lower || d.toLowerCase().includes(lower))) {
      if (STATE_CENTROIDS[state]) return STATE_CENTROIDS[state];
    }
  }

  // 4. Fallback to provided stateName centroid
  if (stateName && STATE_CENTROIDS[stateName]) {
    return STATE_CENTROIDS[stateName];
  }

  return { lat: 28.6139, lng: 77.209 };
}

